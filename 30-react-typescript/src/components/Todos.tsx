import React from 'react';

import TodoItem from './TodoItem.tsx';
import Todo from '../models/todo.ts';

const Todos: React.FC<{ items: Todo[] }> = (props) => {
  return (
    <ul>
      {props.items.map((item) => (
        <TodoItem key={item.id} text={item.text} />
      ))}
    </ul>
  );
};

export default Todos;
